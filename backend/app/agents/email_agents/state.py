from typing import TypedDict, List, Dict, Any, Optional, Annotated
import operator
from pydantic import BaseModel, Field


class EmailDraft(BaseModel):
    """Represents a draft email waiting for human assistance/approval."""
    action_type: str = Field(
        default="send",
        description="Type of email action: 'send' (new email), 'reply' (reply to thread), or 'followup' (follow-up reminder)"
    )
    to: str = Field(default="", description="Recipient email address")
    subject: str = Field(default="", description="Email subject")
    body: str = Field(default="", description="Draft body text")
    thread_id: Optional[str] = Field(default=None, description="Gmail threadId if replying or following up")
    message_id: Optional[str] = Field(default=None, description="Gmail message ID if replying or following up")


class EmailAgentState(TypedDict):
    """LangGraph state for the email assistant system."""
    # Conversation messages
    messages: Annotated[List[Dict[str, Any]], operator.add]

    # Classified intent: 'read', 'send', 'reply', 'followup', 'approval_response', or 'chat'
    intent: Optional[str]

    # Search parameters
    search_query: Optional[str]

    # Retrieved emails or thread records
    emails: List[Dict[str, Any]]

    # Draft generated by the agent awaiting user assistance/approval
    draft: Optional[Dict[str, Any]]

    # User review state: 'pending', 'approved', 'rejected', 'revised'
    approval_status: Optional[str]

    # User's comments or edit requests during review
    user_feedback: Optional[str]

    # Execution result after sending or reading
    result: Optional[Dict[str, Any]]

    # Final text message to present to the user
    final_response: Optional[str]
